"""
Orchestrates incoming Instagram Messaging webhook processing, delivery receipts,
AI generation, safety policy enforcement, and automatic outbound dispatch.
Ref: https://developers.facebook.com/docs/messenger-platform/instagram/webhooks
"""

import logging
from typing import Any

from sqlalchemy.orm import Session

from app.ai.engine import AIEngine
from app.ai.schemas import GenerateReplyRequest
from app.integrations.instagram.adapter import InstagramAdapter
from app.integrations.instagram.models import InstagramWebhookPayload
from app.models.enums import AccountType, PlatformType
from app.repositories.account_repo import AccountRepository
from app.schemas.conversation import MessageCreate
from app.schemas.safety import PolicyAction
from app.services.conversation_service import ConversationService
from app.services.knowledge_service import KnowledgeService
from app.services.safety_service import SafetyService

logger = logging.getLogger("aashrayspa.integrations.instagram.webhook")


def process_instagram_webhook(
    payload_dict: dict[str, Any],
    db: Session,
    adapter: InstagramAdapter,
) -> dict[str, Any]:
    """
    Main entry point for processing verified Instagram Messaging API webhook events.
    """
    try:
        payload = InstagramWebhookPayload.model_validate(payload_dict)
    except Exception as exc:
        logger.error(f"Invalid Instagram webhook payload schema: {exc}")
        return {"status": "ignored", "reason": "invalid_schema"}

    account_repo = AccountRepository(db)
    conv_service = ConversationService(db)
    safety_service = SafetyService(db)
    knowledge_service = KnowledgeService(db)
    ai_engine = AIEngine()

    processed_messages_count = 0
    status_updates_count = 0

    for entry in payload.entry:
        entry_id = entry.id

        # ── 1. Strict Account Identification ──────────────────────────
        # Lookup Account by platform_account_id or fallback to Business Instagram
        account = account_repo.get_by_platform_account_id(entry_id)
        if not account:
            ig_accounts = account_repo.get_all(
                platform=PlatformType.INSTAGRAM.value,
                account_type=AccountType.BUSINESS.value,
            )
            account = ig_accounts[0] if ig_accounts else None

        if not account:
            logger.error(f"No configured Instagram business account matches entry id '{entry_id}'")
            continue

        for messaging_event in entry.messaging:
            # ── 2. Handle Read & Delivery Receipts ────────────────────
            if messaging_event.read:
                read_mid = messaging_event.read.mid
                if read_mid:
                    msg = conv_service.repo.get_message_by_platform_id(read_mid)
                    if msg:
                        msg.delivery_status = "read"
                        db.commit()
                        status_updates_count += 1
                        logger.info(f"Updated Instagram message '{read_mid}' delivery_status to 'read'")

            if messaging_event.delivery:
                del_mids = messaging_event.delivery.mids or []
                for mid in del_mids:
                    msg = conv_service.repo.get_message_by_platform_id(mid)
                    if msg:
                        msg.delivery_status = "delivered"
                        db.commit()
                        status_updates_count += 1
                        logger.info(f"Updated Instagram message '{mid}' delivery_status to 'delivered'")

            # ── 3. Handle Inbound Message ─────────────────────────────
            if messaging_event.message:
                in_msg = messaging_event.message

                # Skip echo messages generated by the account owner or other automated tools
                if in_msg.is_echo:
                    logger.info(f"Skipping Instagram echo message '{in_msg.mid}'")
                    continue

                # Idempotency check: Skip duplicate webhook delivery
                if safety_service.is_duplicate_webhook(in_msg.mid):
                    logger.info(f"Duplicate Instagram webhook event '{in_msg.mid}' ignored.")
                    continue

                # Record raw incoming webhook event
                event_record = safety_service.webhook_repo.record_event(
                    platform="instagram",
                    event_type="message",
                    platform_event_id=in_msg.mid,
                    raw_payload=payload_dict,
                    account_id=account.id,
                )

                sender_id = messaging_event.sender.id
                message_text = in_msg.text or ""

                if not message_text:
                    safety_service.webhook_repo.mark_processed(
                        event_record, status="skipped", error="Non-text message"
                    )
                    continue

                # ── A. Resolve Contact & Conversation ─────────────────
                display_name = f"IG User {sender_id[-6:]}" if len(sender_id) >= 6 else f"IG User {sender_id}"
                contact = conv_service.get_or_create_contact(
                    account_id=account.id,
                    platform_contact_id=sender_id,
                    display_name=display_name,
                )
                conv = conv_service.get_or_create_conversation(
                    account_id=account.id, contact_id=contact.id
                )

                # ── B. Record Inbound Message ─────────────────────────
                conv_service.record_message(
                    conversation_id=conv.id,
                    data=MessageCreate(
                        platform_message_id=in_msg.mid,
                        direction="inbound",
                        content=message_text,
                        sender_type="contact",
                        delivery_status="received",
                    ),
                )

                # ── C. Sliding Window History Context ─────────────────
                history = conv_service.get_conversation_context(
                    conv.id, limit=account.context_window_size
                )

                # ── D. Verified Business Knowledge ───────────────────
                biz_context = knowledge_service.compile_knowledge_for_account(account.id)

                # ── E. AI Engine Response Generation ──────────────────
                gen_req = GenerateReplyRequest(
                    account_id=account.id,
                    message=message_text,
                    sender_name=display_name,
                    conversation_history=history[:-1] if history else [],
                    business_context=biz_context,
                )
                ai_reply = ai_engine.process_message(account=account, request=gen_req)

                # ── F. Server-Side Safety Policy Evaluation ───────────
                policy_decision = safety_service.evaluate_outbound_policy(
                    account=account,
                    ai_response=ai_reply,
                    conversation_id=conv.id,
                )

                # ── G. Outbound Dispatch Action ───────────────────────
                if policy_decision.action == PolicyAction.SEND_AUTOMATIC:
                    dispatch_res = adapter.send_text_message(
                        recipient_id=sender_id,
                        text=ai_reply.reply,
                        account_id=account.id,
                    )

                    igmid = None
                    if dispatch_res.get("success"):
                        data = dispatch_res.get("data", {})
                        igmid = data.get("message_id")

                    # Record dispatched outbound message
                    conv_service.record_message(
                        conversation_id=conv.id,
                        data=MessageCreate(
                            platform_message_id=igmid,
                            direction="outbound",
                            content=ai_reply.reply,
                            sender_type="assistant",
                            delivery_status="sent" if dispatch_res.get("success") else "failed",
                            is_ai_generated=True,
                            owner_approved=True,
                            ai_metadata=ai_reply.model_dump(),
                        ),
                    )

                    # Qualify and capture advertising lead
                    safety_service.capture_lead_if_qualified(
                        account=account,
                        conversation_id=conv.id,
                        contact_id=contact.id,
                        ai_response=ai_reply,
                        customer_name=display_name,
                        incoming_message=message_text,
                    )

                elif policy_decision.action in (
                    PolicyAction.QUEUE_FOR_APPROVAL,
                    PolicyAction.ESCALATE,
                ):
                    # Persist draft for owner review
                    conv_service.record_message(
                        conversation_id=conv.id,
                        data=MessageCreate(
                            direction="outbound",
                            content=ai_reply.reply,
                            sender_type="assistant",
                            delivery_status="pending",
                            is_ai_generated=True,
                            owner_approved=False,
                            ai_metadata={
                                **ai_reply.model_dump(),
                                "policy_action": policy_decision.action.value,
                                "policy_reason": policy_decision.reason,
                            },
                        ),
                    )

                # Mark webhook processed
                safety_service.webhook_repo.mark_processed(event_record, status="processed")
                processed_messages_count += 1

    return {
        "status": "success",
        "processed_messages": processed_messages_count,
        "status_updates": status_updates_count,
    }
